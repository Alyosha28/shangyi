#!/usr/bin/env bash
# 把 token 表和外壳源码拼成 DSH 客户端 bundle：lib/client.js
# 为什么不做打包：DSH 的客户端插件契约就是「一个登记 __ModuleLoader__ 的普通脚本」，
# 没有 import/export，也就不需要 bundler。拼装顺序固定：先 token 表，后外壳。
set -euo pipefail
cd "$(dirname "$0")/.."
{
  echo "// AUTO-GENERATED by scripts/build.sh — 改 src/shell.js 或 lib/tokens.gen.js 后重跑。"
  echo "// tokens.gen.js 由 scripts/gen-tokens.py 从 DSH 默认主题实测快照推导。"
  echo
  cat lib/tokens.gen.js
  echo
  cat src/shell.js
} > lib/client.js
node --check lib/client.js 2>&1 || { echo "语法检查失败"; exit 1; }
echo "built lib/client.js ($(wc -l < lib/client.js) 行, $(wc -c < lib/client.js) 字节)"
