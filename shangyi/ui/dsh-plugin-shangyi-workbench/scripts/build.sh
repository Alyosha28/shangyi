#!/usr/bin/env bash
# 把 src/ 下的分片按文件名顺序拼成 DSH 客户端 bundle：lib/client.js
#
# 为什么不做打包：DSH 的客户端插件契约就是「一个登记 __ModuleLoader__ 的普通脚本」，
# React 由 require('react') 从浏览器模块表取，没有 import/export 需要处理。
# 分片顺序固定（00-head 打开 factory，90-tail 关闭），文件名前缀就是这个顺序。
set -euo pipefail
cd "$(dirname "$0")/.."

ICONS_EMBED="../shangyi-icons/dist/embedded.js"
if [[ ! -f "$ICONS_EMBED" ]]; then
  echo "缺少 $ICONS_EMBED，先运行 node ../shangyi-icons/scripts/build-embedded.mjs ..." >&2
  node ../shangyi-icons/scripts/build-embedded.mjs
fi

mkdir -p lib
{
  echo "// AUTO-GENERATED by scripts/build.sh — 改 src/*.js 或 shangyi-icons 后重跑，不要手改本文件。"
  echo
  echo "// ===== shangyi-icons/dist/embedded.js ====="
  echo "(function () {"
  cat "$ICONS_EMBED"
  echo "})();"
  for f in src/*.js; do
    echo
    echo "// ===== ${f#src/} ====="
    cat "$f"
  done
} > lib/client.js

node --check lib/client.js || { echo "node --check 失败：lib/client.js 语法错误" >&2; exit 1; }
echo "built lib/client.js ($(wc -l < lib/client.js | tr -d ' ') 行, $(wc -c < lib/client.js | tr -d ' ') 字节)"
